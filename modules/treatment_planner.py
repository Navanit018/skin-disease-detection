def get_personalized_plan(skin_type, age=None, concerns=None):
    morning = MORNING_ROUTINE_TEMPLATES.get(skin_type, MORNING_ROUTINE_TEMPLATES['Normal'])
    night = NIGHT_ROUTINE_TEMPLATES.get(skin_type, NIGHT_ROUTINE_TEMPLATES['Normal'])
    diet = DIET_TIPS.get(skin_type, DIET_TIPS['Normal'])

    if age and age > 40:
        morning = [step for step in morning]
        night = list(night)
        night.insert(4, ('Step 4.5', 'Anti-Aging', 'Apply retinol or prescription retinoid'))

    if concerns:
        if any('acne' in c.lower() for c in concerns):
            morning = [step for step in morning]
            night = list(night)
            if skin_type == 'Oily':
                night.insert(3, ('Step 3.5', 'Acne Treatment', 'Benzoyl peroxide spot treatment'))

        if any('pigment' in c.lower() or 'dark spot' in c.lower() or 'hyperpigmentation' in c.lower() for c in concerns):
            morning = list(morning)
            morning.insert(3, ('Step 3.5', 'Brighten', 'Vitamin C or Alpha arbutin serum'))

    return {
        'morning_routine': morning,
        'night_routine': night,
        'diet_suggestions': diet,
        'lifestyle_tips': LIFESTYLE_TIPS
    }

